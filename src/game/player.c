void ChangeLevel(void)
{
    if(!allow_lcs) return;
    if(pressed(joy_edge,FIRE_A) && pressed(joy_cur,OPTION)){ s16 n=(s16)(cur_level+1);if(n>AVP_MAX_LEVEL)n=1;new_level=n; }
    else if(pressed(joy_edge,FIRE_B) && pressed(joy_cur,OPTION)){ s16 n=(s16)(cur_level-1);if(n<1)n=AVP_MAX_LEVEL;new_level=n; }
}
