static const u16 nrg_maxes[3]={MNRG_MAX,ANRG_MAX,PNRG_MAX};
/* Exact 16-entry CRY pain-colour ramps generated by the source `pain` macro. */
static const u16 human_pain[16]={0x8780,0x8784,0x9688,0x968c,0xa590,0xa594,0xb498,0xb49c,0xc3a0,0xc3a4,0xd2a8,0xd2ac,0xe1b0,0xe1b4,0xf0b8,0xf0bc};
